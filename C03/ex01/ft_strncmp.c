int	ft_strncmp(char *s1, char *s2, unsigned int n)
{
	unsigned int	x;

	if ( n == 0)
	{
		return (0);
	}
	x = 0;
	while (x < n -1  && s1[x] && s2[x] && s1[x] == s2[x])
	{
		x++;
	}
	return (s1[x] - s2[x]);
}
